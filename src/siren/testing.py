"""Try an app's request handler without Siren.

:func:`app_request` builds a request signed the way Siren signs one, for any
kind of feature, and :func:`sample_data` gives each kind's example question,
the one Siren's own request fixture holds. :func:`webhook_event` signs a
webhook event as Siren sends one to an app's address, with
:func:`sample_event_data` for its payload, and :func:`app_request_from_record`
turns a request Siren stored back into a test input. Hand any of them to the
handler's ``simulate()`` in a test, which runs the function and returns its
answer without posting it, or post one to a running app with any HTTP
client::

    from siren.testing import app_request

    def test_split_by_score():
        result = answers.simulate(app_request("distributionResolver", "split-by-score"))
        assert result.answer["shares"] == {"41": 6000, "43": 4000}

Nothing here reaches the network.
"""

from __future__ import annotations

import copy
import hashlib
import hmac
import json
import os
import re
import time
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Dict, Mapping, Optional, Tuple, Union

from ._client import default_base_url
from .apps import REQUEST_EVENT, _REQUEST_ID
from .errors import AppHandlerError
from .types import APP_KINDS

__all__ = [
    "EVENT_TYPES",
    "KINDS",
    "AppTestRequest",
    "app_request",
    "app_request_from_record",
    "sample_data",
    "sample_event_data",
    "webhook_event",
]

_SAMPLES: Dict[str, Dict[str, Any]] = json.loads((Path(__file__).parent / "_samples.json").read_text(encoding="utf-8"))["kinds"]

#: The kinds Siren sends an app a request for, each with sample data.
KINDS: Tuple[str, ...] = tuple(sorted(_SAMPLES))

_TELLS = frozenset(entry["kind"] for entry in APP_KINDS if entry["mode"] == "tell")

# Generated by scripts/siren_event_samples.py from Siren's
# docs/api/webhooks-events.md. tests/test_dx_pass4.py holds it to that file.
_EVENT_SAMPLES: Dict[str, Dict[str, Any]] = json.loads(
    (Path(__file__).parent / "_event_samples.json").read_text(encoding="utf-8")
)["events"]

#: The webhook events Siren documents a payload for, each with sample data.
EVENT_TYPES: Tuple[str, ...] = tuple(sorted(_EVENT_SAMPLES))

_EVENT_TYPE = re.compile(r"^[a-z_]+\.[a-z_]+$")


@dataclass(frozen=True)
class AppTestRequest:
    """A signed request, as Siren would send it: ``method``, ``headers`` and
    the ``raw_body`` bytes the signature covers. Pass it to the handler's
    ``simulate()``, or post ``raw_body`` with ``headers`` to a running app."""

    method: str
    headers: Dict[str, str] = field(default_factory=dict)
    raw_body: bytes = b""

    @property
    def body(self) -> Dict[str, Any]:
        """The request's body, parsed."""
        parsed: Dict[str, Any] = json.loads(self.raw_body)
        return parsed

    @classmethod
    def signed(
        cls, raw_body: bytes, secret: str, *, timestamp: Optional[int] = None, event: str = REQUEST_EVENT
    ) -> "AppTestRequest":
        """Any body, signed as Siren signs a request. For a test that sends
        the handler something Siren would not, such as a broken body.
        ``event`` is the ``X-Siren-Event`` header, ``app.request`` by
        default."""
        t = int(time.time()) if timestamp is None else int(timestamp)
        v1 = hmac.new(secret.encode("utf-8"), f"{t}.".encode("utf-8") + raw_body, hashlib.sha256).hexdigest()
        headers = {
            "Content-Type": "application/json",
            "X-Siren-Event": event,
            "X-Siren-Timestamp": str(t),
            "X-Siren-Signature-V2": f"t={t},v1={v1}",
        }
        return cls("POST", headers, raw_body)


def sample_data(kind: str) -> Dict[str, Any]:
    """The kind's example question, the ``data`` Siren's own request fixture
    holds for it. Each call returns a fresh copy, so change it freely.

    Raises :class:`ValueError` for a kind Siren sends no request for.
    """
    if kind not in _SAMPLES:
        raise ValueError(f"siren.testing has no sample for {kind!r}. Siren sends requests for these kinds: {', '.join(KINDS)}.")
    return copy.deepcopy(_SAMPLES[kind])


def app_request(
    kind: str,
    key: str,
    *,
    data: Optional[Mapping[str, Any]] = None,
    secret: Optional[str] = None,
    id: Optional[str] = None,  # noqa: A002 - the request's own field name
    app: str = "my-app",
    base_url: Optional[str] = None,
    timestamp: Optional[int] = None,
    test: bool = False,
) -> AppTestRequest:
    """A request for the feature ``key`` of ``kind``, signed as Siren signs
    one.

    - ``data`` is the question, :func:`sample_data` for the kind by default.
    - ``secret`` is the app's signing secret, ``SIREN_SIGNING_SECRET`` by
      default.
    - ``id`` is the request key, a new ``apr_`` id by default.
    - ``base_url`` is the Siren the request comes from. An ask's
      ``answerUrl`` is built on it. It defaults as the client's does, to
      ``SIREN_BASE_URL`` and then Siren Cloud's address.
    - ``timestamp`` is the signed time in Unix seconds, now by default.
    - ``test=True`` builds a test request, as ``siren trigger ask`` makes
      Siren send: the body carries ``"test": true`` after ``mode``, and the
      handler reads ``request.test`` as true. Left out, the field is absent,
      as on a real request.

    The two actions are tells and every other kind is an ask, with
    ``answerBy`` an hour after the request was made.

    Raises :class:`ValueError` for a kind Siren sends no request for, an
    empty key, a malformed id, and no secret.
    """
    method = "siren.testing.app_request()"
    question = sample_data(kind) if data is None else dict(data)
    if not isinstance(key, str) or key == "":
        raise ValueError(f"{method} needs the feature's key, such as 'split-by-score'.")
    signing_secret = _secret(method, secret)
    request_id = f"apr_{uuid.uuid4().hex}" if id is None else id
    if not isinstance(request_id, str) or not _REQUEST_ID.match(request_id):
        raise ValueError(f"{method} takes id as apr_ followed by 32 lowercase hex characters, and got {request_id!r}.")

    t = int(time.time()) if timestamp is None else int(timestamp)
    made = datetime.fromtimestamp(t, tz=timezone.utc)
    body: Dict[str, Any] = {
        "version": 1,
        "id": request_id,
        "type": REQUEST_EVENT,
        "mode": "tell" if kind in _TELLS else "ask",
    }
    if test is True:
        body["test"] = True
    body["app"] = app
    body["feature"] = {"kind": kind, "key": key, "id": "app:1"}
    body["createdAt"] = made.isoformat()
    if body["mode"] == "ask":
        body["answerBy"] = (made + timedelta(hours=1)).isoformat()
        body["answerUrl"] = f"{(base_url or default_base_url()).rstrip('/')}/apps/requests/{request_id}/answer"
    body["data"] = question
    return _request(body, signing_secret, t)


def _request(body: Dict[str, Any], secret: str, t: int) -> AppTestRequest:
    """An app request's body, signed, with the delivery headers of its first send."""
    request = AppTestRequest.signed(json.dumps(body).encode("utf-8"), secret, timestamp=t)
    request.headers["X-Siren-Delivery"] = f"{body['id']}.1"
    request.headers["Idempotency-Key"] = body["id"]
    return request


def _secret(method: str, given: Optional[str]) -> str:
    """The signing secret given, or ``SIREN_SIGNING_SECRET``."""
    secret = given if given is not None else os.environ.get("SIREN_SIGNING_SECRET")
    if not secret:
        raise ValueError(f"{method} needs the app's signing secret. Pass secret, or set SIREN_SIGNING_SECRET.")
    return secret


def sample_event_data(type: str) -> Dict[str, Any]:  # noqa: A002 - the event's own field name
    """Siren's sample ``data`` for the webhook event ``type``, built from the
    payload table Siren's event reference gives it
    (docs/api/webhooks-events.md). Each call returns a fresh copy.

    Raises :class:`ValueError` for an event Siren documents no payload for,
    such as ``credit.issued``. Pass that event's data to
    :func:`webhook_event` yourself.
    """
    if type not in _EVENT_SAMPLES:
        raise ValueError(
            f"siren.testing has no sample of {type!r}. Pass the data to webhook_event(type, data). "
            f"It has samples of {', '.join(EVENT_TYPES)}."
        )
    return copy.deepcopy(_EVENT_SAMPLES[type])


def webhook_event(
    type: str,  # noqa: A002 - the event's own field name
    data: Optional[Mapping[str, Any]] = None,
    *,
    secret: Optional[str] = None,
    delivery_id: Optional[str] = None,
    timestamp: Optional[int] = None,
) -> AppTestRequest:
    """A webhook event of ``type``, signed as Siren signs one to an app's
    address: the body is the event's data, ``X-Siren-Event`` names the type,
    and ``X-Siren-Delivery`` is a new ``evt_`` id. Hand it to the handler's
    ``simulate()`` to test an ``on_event()`` function.

    - ``data`` is the payload, :func:`sample_event_data` for the type by
      default.
    - ``secret`` is the app's signing secret, ``SIREN_SIGNING_SECRET`` by
      default.
    - ``delivery_id`` is the ``X-Siren-Delivery`` header.
    - ``timestamp`` is the signed time in Unix seconds, now by default.

    Raises :class:`ValueError` for a type that is not ``<noun>.<verb>`` in
    lowercase, no data for an event Siren documents none for, and no secret.
    """
    method = "siren.testing.webhook_event()"
    if not isinstance(type, str) or not _EVENT_TYPE.match(type):
        raise ValueError(f"{method} takes an event type such as conversion.approved, and {type!r} is not one.")
    payload = sample_event_data(type) if data is None else dict(data)
    signing_secret = _secret(method, secret)
    t = int(time.time()) if timestamp is None else int(timestamp)
    raw_body = json.dumps(payload).encode("utf-8")
    event = AppTestRequest.signed(raw_body, signing_secret, timestamp=t, event=type)
    event.headers["X-Siren-Delivery"] = f"evt_{uuid.uuid4().hex}" if delivery_id is None else delivery_id
    event.headers["X-Siren-Signature"] = "sha256=" + hmac.new(signing_secret.encode("utf-8"), raw_body, hashlib.sha256).hexdigest()
    event.headers["User-Agent"] = "Siren-Webhooks/1.0"
    return event


def app_request_from_record(
    record: Union[Mapping[str, Any], str, bytes],
    *,
    key: Optional[str] = None,
    secret: Optional[str] = None,
    app: Optional[str] = None,
    base_url: Optional[str] = None,
    timestamp: Optional[int] = None,
) -> AppTestRequest:
    """A request Siren stored, as a test input: the same id, kind, mode,
    ``test``, data and ``answerBy`` Siren sent, signed again so the
    handler's ``simulate()`` takes it.

    ``record`` is a stored request as Siren's ``GET /apps/requests/{id}``
    answers it (``AppRequestSerializer::toDetail()``), such as the file
    ``siren apps requests <id> --json > request.json`` saves with a signed-in
    session, or a raw request body as the app logged it. Either one parsed,
    or its JSON text. Siren refuses an app's key on that route.

    - ``key`` is the feature's key. A key passed in wins over the record's,
      as in Node, so a request replays against a renamed feature. Without
      one, the saved file's ``featureKey`` is used, or a raw body's
      ``feature``. Siren's own row names its feature as ``app:12`` only, and
      the file's ``featureKey`` is null once the app is gone, so pass the key
      ``siren apps show <app>`` lists beside the feature.
    - ``secret`` is the app's signing secret, ``SIREN_SIGNING_SECRET`` by
      default.
    - ``app`` is the app's key: the file's ``appKey``, the record's ``app``
      or ``my-app`` by default.
    - ``base_url`` and ``timestamp`` are as for :func:`app_request`.

    Raises :class:`ValueError` for a record that is not a stored request,
    and no secret. Raises :class:`~siren.AppHandlerError` for a stored row
    with no ``key``, as the Node and PHP SDKs do.
    """
    method = "siren.testing.app_request_from_record()"
    row: Any = record
    if isinstance(record, (str, bytes)):
        try:
            row = json.loads(record)
        except ValueError:
            raise ValueError(f"{method} takes a stored request as a dict or its JSON text, and this text is not JSON.") from None
    if not isinstance(row, Mapping):
        raise ValueError(f"{method} takes a stored request as a dict, such as what `siren apps requests <id> --json` saves.")
    feature = row.get("feature")
    envelope: Mapping[str, Any] = feature if isinstance(feature, Mapping) else {}
    kind = envelope.get("kind", row.get("kind"))
    feature_id = envelope.get("id") if envelope else feature
    mode = row.get("mode")
    request_id = row.get("id")
    if not isinstance(request_id, str) or not isinstance(kind, str) or mode not in ("ask", "tell"):
        raise ValueError(f"{method} needs the record's id, kind and mode, as `siren apps requests <id> --json` saves them.")
    saved_key = row.get("featureKey")
    if key is not None and key != "":
        feature_key: Any = key
    elif isinstance(saved_key, str) and saved_key != "":
        feature_key = saved_key
    else:
        feature_key = envelope.get("key")
    if not isinstance(feature_key, str) or feature_key == "":
        gone = " Its featureKey is null, as when the app is gone." if "featureKey" in row else ""
        raise AppHandlerError(
            f"{method} needs the feature's key: the record names its feature as {feature_id}, without the key.{gone} "
            "Pass key, which `siren apps show <app>` lists beside each feature."
        )
    signing_secret = _secret(method, secret)
    t = int(time.time()) if timestamp is None else int(timestamp)
    made = datetime.fromtimestamp(t, tz=timezone.utc)
    body: Dict[str, Any] = {"version": 1, "id": request_id, "type": REQUEST_EVENT, "mode": mode}
    if row.get("test") is True:
        body["test"] = True
    saved_app = next((row[name] for name in ("appKey", "app") if isinstance(row.get(name), str) and row[name]), "my-app")
    body["app"] = app if app is not None else saved_app
    body["feature"] = {"kind": kind, "key": feature_key, "id": feature_id if isinstance(feature_id, str) else "app:1"}
    body["createdAt"] = row["createdAt"] if isinstance(row.get("createdAt"), str) else made.isoformat()
    if mode == "ask":
        answer_by = row.get("answerBy")
        body["answerBy"] = answer_by if isinstance(answer_by, str) else (made + timedelta(hours=1)).isoformat()
        body["answerUrl"] = f"{(base_url or default_base_url()).rstrip('/')}/apps/requests/{request_id}/answer"
    data = row.get("data")
    body["data"] = dict(data) if isinstance(data, Mapping) else {}
    return _request(body, signing_secret, t)
