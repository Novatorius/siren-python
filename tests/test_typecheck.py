"""DX pass 3, findings 1 and 3, checked the way a developer's editor checks
them: mypy --strict on small files that use the SDK.

- typos.py holds the review's two mistakes, a misspelled question field and a
  misspelled outcome, and mypy must name both lines.
- correct.py spells them right and uses the other forms of ``on()``, and
  mypy must pass it.
- wrong_kind.py annotates a function with another kind's question, which the
  generated overload of ``on()`` refuses.
- The fixture module holds Siren's own request and answer for every kind
  (tests/fixtures/apps-feature-contracts/requests.json), plus the branches
  Siren's builders allow and the fixture lacks, each assigned to the SDK's
  type, the way Node's types are checked with ``satisfies``.

mypy runs once for all of them. The test skips when mypy is not installed.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, List

import pytest

import siren

pytest.importorskip("mypy")

HERE = Path(__file__).parent
FILES = HERE / "typecheck"
CONTRACTS = json.loads((HERE / "fixtures" / "apps-feature-contracts" / "requests.json").read_text())

QUESTION = {
    "postConversionAction": "PostConversionActionTell",
    "postAllocationAction": "PostAllocationActionTell",
    "distributionResolver": "DistributionResolverQuestion",
    "incentiveResolver": "IncentiveResolverQuestion",
    "incentiveType": "IncentiveTypeQuestion",
    "metricCalculation": "MetricCalculationQuestion",
    "metricFilter": "MetricFilterQuestion",
    "transactionFilter": "TransactionFilterQuestion",
    "engagementCalculation": "EngagementCalculationQuestion",
    "engagementFilter": "EngagementFilterQuestion",
    "programGroupSorter": "ProgramGroupSorterQuestion",
    "collaboratorGroupStructure": "CollaboratorGroupStructureQuestion",
    "payoutMethod": "PayoutMethodQuestion",
}


def _branches() -> List[tuple]:
    """Shapes Siren's builders send that the fixture's one example per kind
    lacks, each as (kind, type, data)."""
    kinds = CONTRACTS["kinds"]
    no_reward = dict(kinds["postConversionAction"]["request"]["data"], reward=None)
    no_currency = json.loads(json.dumps(kinds["transactionFilter"]["request"]["data"]))
    no_currency["transaction"]["currency"] = None
    lead = dict(kinds["incentiveResolver"]["request"]["data"], transaction=None, reason="refund")
    lead_type = dict(kinds["incentiveType"]["request"]["data"], transaction=None, binding={"type": "lead", "id": "L-1"})
    refund_type = dict(kinds["incentiveType"]["request"]["data"], reason="refund", conversions=[{"conversionId": 1042, "engagementId": 880}])
    no_args = dict(kinds["engagementCalculation"]["request"]["data"], args={})
    engagement = kinds["engagementCalculation"]["request"]["data"]
    group = kinds["collaboratorGroupStructure"]["request"]["data"]
    program_group = {
        "group": group["group"],
        "members": group["members"],
        "for": {"type": "program", "id": 3},
        "triggeringCollaborator": group["triggeringCollaborator"],
        "program": engagement["program"],
        "engagementType": engagement["engagementType"],
        "programEngagementTypeId": engagement["programEngagementTypeId"],
        "args": {},
        "opportunity": engagement["opportunity"],
        "cause": engagement["cause"],
    }
    sale_metric = dict(kinds["metricCalculation"]["request"]["data"], sale={"transactionId": 3307, "conversionId": None, "excludedLineIds": [5502]})
    return [
        ("postConversionAction", "PostConversionActionTell", no_reward),
        ("transactionFilter", "TransactionFilterQuestion", no_currency),
        ("incentiveResolver", "IncentiveResolverQuestion", lead),
        ("incentiveType", "IncentiveTypeQuestion", lead_type),
        ("incentiveType", "IncentiveTypeQuestion", refund_type),
        ("engagementCalculation", "EngagementCalculationQuestion", no_args),
        ("collaboratorGroupStructure", "CollaboratorGroupStructureProgramQuestion", program_group),
        ("metricCalculation", "MetricCalculationQuestion", sale_metric),
    ]


def _fixture_module() -> str:
    lines = ['"""Generated by tests/test_typecheck.py from Siren\'s request fixture."""', "", "import siren", ""]
    for kind, entry in sorted(CONTRACTS["kinds"].items()):
        lines.append(f"q_{kind}: siren.{QUESTION[kind]} = {entry['request']['data']!r}")
        if entry.get("answer") is not None:
            answer = QUESTION[kind].replace("Question", "Answer")
            lines.append(f"a_{kind}: siren.{answer} = {entry['answer']!r}")
    for number, (kind, name, data) in enumerate(_branches()):
        lines.append(f"b{number}_{kind}: siren.{name} = {data!r}")
    return "\n".join(lines) + "\n"


@pytest.fixture(scope="module")
def mypy(tmp_path_factory) -> Dict[str, List[str]]:
    """mypy --strict's errors, by file name."""
    work = tmp_path_factory.mktemp("typecheck")
    for source in FILES.glob("*.py"):
        (work / source.name).write_text(source.read_text())
    (work / "fixture_types.py").write_text(_fixture_module())
    run = subprocess.run(
        [sys.executable, "-m", "mypy", "--strict", "--no-incremental", "--cache-dir", str(work / ".cache"), "--no-color-output",
         "--hide-error-context", "--show-error-codes", *sorted(p.name for p in work.glob("*.py"))],
        cwd=work,
        # Check the siren package this test run imported, not whichever one
        # the interpreter would find on its own.
        env={**os.environ, "MYPYPATH": str(Path(siren.__file__).resolve().parent.parent)},
        capture_output=True,
        text=True,
        timeout=600,
    )
    errors: Dict[str, List[str]] = {}
    for line in run.stdout.splitlines():
        found = re.match(r"^([\w.]+):(\d+): error: (.*)$", line)
        if found:
            errors.setdefault(found.group(1), []).append(f"{found.group(2)}: {found.group(3)}")
    assert run.returncode in (0, 1), run.stdout + run.stderr
    return errors


def _line(name: str, marker: str) -> str:
    for number, text in enumerate((FILES / name).read_text().splitlines(), start=1):
        if marker in text:
            return str(number)
    raise AssertionError(f"{marker} is not in {name}")


def test_mypy_names_the_misspelled_field_and_outcome(mypy):
    errors = mypy.get("typos.py", [])
    field = _line("typos.py", "typo: pool")
    outcome = _line("typos.py", "typo: allocated")
    assert any(e.startswith(f"{field}: ") and '"pools"' in e for e in errors), errors
    assert any(e.startswith(f"{outcome}: ") and "'allocate'" in e for e in errors), errors
    assert len(errors) == 2, errors


def test_mypy_passes_the_function_spelled_right(mypy):
    assert mypy.get("correct.py", []) == []


def test_mypy_refuses_another_kinds_question_on_a_kind(mypy):
    errors = mypy.get("wrong_kind.py", [])
    assert any(e.startswith(_line("wrong_kind.py", "wrong kind") + ": ") for e in errors), errors


def test_sirens_fixture_and_its_branches_fit_the_types(mypy):
    assert mypy.get("fixture_types.py", []) == []
